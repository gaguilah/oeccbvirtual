-- ---------------------------------------------------------------------------------------------
-- Consulta de otros usuarios (Usuarios → "Ver información personal"), solo lectura.
-- ---------------------------------------------------------------------------------------------
-- security definer porque la tabla solo deja ver la fila propia. Exige usuarios.datos_personales
-- sobre el juzgado del usuario consultado: un rol de alcance 'court' solo ve a los de su juzgado.
-- Para usuarios sin juzgado se pasa 0 (no es un juzgado), así ese rol no los ve y uno de alcance
-- 'all' sí. Sin fila devuelve los datos vacíos (Sin registrar).
create or replace function public.get_user_personal_info(p_user_id uuid)
returns table (
  residence_address text,
  mobile_phone text,
  personal_email text,
  eps_name text,
  emergency_name text,
  emergency_relationship text,
  emergency_phone text,
  updated_at timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_court smallint;
begin
  select coalesce(p.court, 0) into v_court from public.profiles p where p.id = p_user_id;

  if not found or not public.has_permission('usuarios.datos_personales', v_court) then
    raise exception 'forbidden' using errcode = '42501', hint = 'Requiere el permiso usuarios.datos_personales.';
  end if;

  return query
    select i.residence_address, i.mobile_phone, i.personal_email, e.name,
      i.emergency_name, i.emergency_relationship, i.emergency_phone, i.updated_at
    from public.profile_personal_info i
    left join public.eps_entities e on e.id = i.eps_id
    where i.user_id = p_user_id;
end;
$$;

revoke execute on function public.get_user_personal_info(uuid) from public, anon;
grant execute on function public.get_user_personal_info(uuid) to authenticated;

