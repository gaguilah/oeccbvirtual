-- EPS.
-- ---------------------------------------------------------------------------------------------
create table if not exists public.eps_entities (
  id smallint generated by default as identity primary key,
  name text not null constraint eps_entities_name_key unique
    constraint eps_entities_name_chk check (char_length(btrim(name)) between 2 and 120),
  -- Grupo de la lista en el formulario; 'otra' va siempre al final.
  regime text not null
    constraint eps_entities_regime_chk check (regime in ('contributivo', 'subsidiado', 'especial', 'otra')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.eps_entities enable row level security;
revoke all on table public.eps_entities from anon, authenticated;
grant select on table public.eps_entities to authenticated;

drop policy if exists eps_entities_select on public.eps_entities;
