-- ---------------------------------------------------------------------------------------------
-- Información personal y contacto de emergencia.
-- ---------------------------------------------------------------------------------------------
create table if not exists public.profile_personal_info (
  user_id uuid primary key references public.profiles (id) on delete cascade,
  residence_address text
    constraint profile_personal_info_address_chk
    check (char_length(residence_address) between 5 and 200 and residence_address !~ '[\r\n]'),
  -- Celular colombiano: 10 dígitos que empiezan por 3, sin espacios (el formulario los quita).
  mobile_phone text
    constraint profile_personal_info_mobile_chk check (mobile_phone ~ '^3[0-9]{9}$'),
  personal_email text
    constraint profile_personal_info_email_chk
    check (
      char_length(personal_email) <= 254
      and personal_email = lower(personal_email)
      and personal_email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
    ),
  eps_id smallint references public.eps_entities (id),
  -- Misma regla que profiles_full_name_format (20261005140000).
  emergency_name text
    constraint profile_personal_info_emergency_name_chk
    check (
      char_length(emergency_name) between 3 and 120
      and emergency_name ~ '^[A-Za-zÀ-ÖØ-öø-ÿ]+((\. |[ ''-])[A-Za-zÀ-ÖØ-öø-ÿ]+)*\.?$'
    ),
  emergency_relationship text
    constraint profile_personal_info_relationship_chk
    check (
      emergency_relationship in (
        'madre', 'padre', 'conyuge', 'hijo', 'hermano', 'otro_familiar', 'amigo', 'otro'
      )
    ),
  emergency_phone text
    constraint profile_personal_info_emergency_phone_chk check (emergency_phone ~ '^3[0-9]{9}$'),
  updated_at timestamptz not null default now()
);

drop trigger if exists profile_personal_info_set_updated_at on public.profile_personal_info;
create trigger profile_personal_info_set_updated_at
  before update on public.profile_personal_info
  for each row execute function public.set_updated_at();

-- Solo la fila propia. Sin delete: "Quitar estos datos" deja la sección en null. Ninguna Edge
