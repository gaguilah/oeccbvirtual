-- Formato "Referencia cruzada" de audiencias realizadas (docs/plan-audiencias-formato.md).
--
-- 1. Catálogo de cargos (job_positions) y cargo en el perfil (profiles.position_id), que cada
--    usuario cambia solo en el suyo, como el nombre.
-- 2. complete_password_change() exige cargo: un usuario nuevo elige su cargo antes de poder usar el
--    dashboard.
-- 3. Quién registró la grabación de una audiencia y cuándo, con copia del nombre y el cargo de ese
--    momento (el formato no cambia si la persona cambia de cargo o de nombre). Lo llena el trigger
--    hearings_recording_author cada vez que cambia recording_url con un usuario; no se escribe desde
--    el navegador (no está en el grant update de hearings).
--
-- Idempotente. Los cargos de los usuarios actuales y las audiencias ya realizadas se cargan con un
-- SQL aparte (no se versiona).

-- ---------------------------------------------------------------------------------------------
-- Cargos.
-- ---------------------------------------------------------------------------------------------
create table if not exists public.job_positions (
  id smallint generated by default as identity primary key,
  name text not null constraint job_positions_name_key unique
    constraint job_positions_name_chk check (char_length(btrim(name)) between 2 and 120),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.job_positions enable row level security;
revoke all on table public.job_positions from anon, authenticated;
grant select on table public.job_positions to authenticated;

drop policy if exists job_positions_select on public.job_positions;
create policy job_positions_select on public.job_positions for select to authenticated using (true);

