-- Cargo del usuario: lo cambia solo él (misma política de fila propia que full_name,
-- 20261005130000). El grant es solo de esta columna.
alter table public.profiles
  add column if not exists position_id smallint references public.job_positions (id);

grant update (position_id) on table public.profiles to authenticated;

-- ---------------------------------------------------------------------------------------------
-- Cambio de contraseña obligatorio: también exige cargo.
-- ---------------------------------------------------------------------------------------------
create or replace function public.complete_password_change()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if exists (select 1 from public.profiles where id = (select auth.uid()) and position_id is null) then
    raise exception 'position_required' using hint = 'Elija su cargo en Mi perfil.';
  end if;
  update public.profiles set must_change_password = false where id = (select auth.uid());
end;
$$;

revoke execute on function public.complete_password_change() from public, anon;
grant execute on function public.complete_password_change() to authenticated;

-- ---------------------------------------------------------------------------------------------
-- Quién registró la grabación.
-- ---------------------------------------------------------------------------------------------
alter table public.hearings
  add column if not exists recording_set_by uuid references auth.users (id) on delete set null,
  add column if not exists recording_set_at timestamptz,
  add column if not exists recording_set_by_name text,
  add column if not exists recording_set_by_position text;

-- Con usuario: si cambia recording_url, guarda quién, cuándo, su nombre y su cargo; si no cambia,
-- conserva lo anterior (no se puede falsificar enviando las columnas). Sin usuario (SQL Editor) no
-- toca nada, así se pueden cargar los datos históricos. Es security definer porque lee auth.users
-- (correo si el perfil no tiene nombre); solo lee datos del propio usuario.
drop function if exists public.hearing_recording_author_of(uuid);

create or replace function public.hearings_recording_author()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
begin
  if v_user is null then
    return new;
  end if;

  if tg_op = 'INSERT' then
    new.recording_set_by := null;
    new.recording_set_at := null;
    new.recording_set_by_name := null;
    new.recording_set_by_position := null;
    return new;
  end if;

  if new.recording_url is distinct from old.recording_url and new.recording_url is not null then
    new.recording_set_by := v_user;
    new.recording_set_at := now();
    select coalesce(nullif(btrim(p.full_name), ''), u.email::text), jp.name
      into new.recording_set_by_name, new.recording_set_by_position
    from auth.users u
    left join public.profiles p on p.id = u.id
    left join public.job_positions jp on jp.id = p.position_id
    where u.id = v_user;
  else
    new.recording_set_by := old.recording_set_by;
    new.recording_set_at := old.recording_set_at;
    new.recording_set_by_name := old.recording_set_by_name;
    new.recording_set_by_position := old.recording_set_by_position;
  end if;
  return new;
end;
$$;

drop trigger if exists hearings_recording_author on public.hearings;
create trigger hearings_recording_author
  before insert or update on public.hearings
  for each row execute function public.hearings_recording_author();

revoke execute on function public.hearings_recording_author() from public, anon, authenticated;
