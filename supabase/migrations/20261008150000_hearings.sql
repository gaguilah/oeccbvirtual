create table if not exists public.hearings (
  id uuid primary key default gen_random_uuid(),
  scheduled_at timestamptz not null,
  hearing_type_id smallint not null references public.hearing_types (id),
  case_number text not null constraint hearings_case_number_chk check (case_number ~ '^[0-9]{23}$'),
  court_id smallint not null references public.execution_courts (id),
  connection_url text constraint hearings_connection_url_chk check (connection_url ~ '^https://\S+$'),
  recording_url text constraint hearings_recording_url_chk check (recording_url ~ '^https://\S+$'),
  status_id smallint not null default 1 references public.hearing_statuses (id),
  notes text constraint hearings_notes_chk check (char_length(notes) <= 1000),
  created_by uuid default auth.uid() references auth.users (id) on delete set null,
  updated_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz,
  -- Un radicado no tiene dos audiencias a la misma fecha y hora.
  constraint hearings_case_scheduled_key unique (case_number, scheduled_at)
);

create index if not exists hearings_scheduled_at_idx on public.hearings (scheduled_at);
create index if not exists hearings_court_scheduled_at_idx on public.hearings (court_id, scheduled_at);

-- Fecha y hora válidas para programar: futura, de lunes a viernes, día hábil, de 7:00 a. m. a
-- 5:00 p. m. (hora de Colombia) y en saltos de 15 minutos.
create or replace function public.hearing_schedule_error(p_scheduled_at timestamptz)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_local timestamp := p_scheduled_at at time zone 'America/Bogota';
begin
  if p_scheduled_at <= now() then
    return 'hearing_past';
  end if;
  if not public.is_business_day(v_local::date) then
    return 'hearing_non_business_day';
  end if;
  if v_local::time < time '07:00' or v_local::time > time '17:00' then
    return 'hearing_out_of_hours';
  end if;
  if extract(minute from v_local)::integer % 15 <> 0 or extract(second from v_local) <> 0 then
    return 'hearing_invalid_minutes';
  end if;
  return null;
end;
$$;

create or replace function public.hearings_rules()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_error text;
begin
  if tg_op = 'DELETE' then
    if v_user is not null
       and not (old.status_id = 1 and old.scheduled_at > now() and old.connection_url is null and old.recording_url is null) then
      raise exception 'hearing_not_deletable'
        using hint = 'Solo se elimina una audiencia programada, futura, sin enlace de conexión ni grabación.';
    end if;
    return old;
  end if;

  if tg_op = 'INSERT' then
    new.created_at := now();
    new.updated_at := null;
    new.updated_by := null;
    if v_user is null then
      return new;
    end if;
    new.created_by := v_user;
    new.status_id := 1;
    v_error := public.hearing_schedule_error(new.scheduled_at);
    if v_error is not null then
      raise exception '%', v_error;
    end if;
    if not exists (select 1 from public.hearing_types t where t.id = new.hearing_type_id and t.is_active) then
      raise exception 'hearing_type_inactive';
    end if;
    if new.recording_url is not null then
      raise exception 'hearing_recording_only_realizada';
    end if;
    return new;
  end if;

  -- UPDATE
  new.created_at := old.created_at;
  new.created_by := old.created_by;
  new.updated_at := now();
  new.updated_by := coalesce(v_user, old.updated_by);
  if v_user is null then
    return new;
  end if;

  -- Cerrada: solo se corrige la grabación de una Realizada.
  if old.status_id <> 1 then
    if (new.scheduled_at, new.hearing_type_id, new.case_number, new.court_id, new.connection_url, new.status_id, new.notes)
       is distinct from
       (old.scheduled_at, old.hearing_type_id, old.case_number, old.court_id, old.connection_url, old.status_id, old.notes)
       or (old.status_id <> 2 and new.recording_url is distinct from old.recording_url) then
      raise exception 'hearing_closed';
    end if;
    if old.status_id = 2 and new.recording_url is null then
      raise exception 'hearing_recording_required';
    end if;
    return new;
  end if;

  if new.status_id = 1 then
    if new.scheduled_at is distinct from old.scheduled_at then
      v_error := public.hearing_schedule_error(new.scheduled_at);
      if v_error is not null then
        raise exception '%', v_error;
      end if;
    end if;
    if new.hearing_type_id is distinct from old.hearing_type_id
       and not exists (select 1 from public.hearing_types t where t.id = new.hearing_type_id and t.is_active) then
      raise exception 'hearing_type_inactive';
    end if;
    if new.recording_url is not null then
      raise exception 'hearing_recording_only_realizada';
    end if;
    return new;
  end if;

  -- Cierre: la fecha y los datos del proceso no cambian al cerrar.
  if (new.scheduled_at, new.hearing_type_id, new.case_number, new.court_id)
     is distinct from (old.scheduled_at, old.hearing_type_id, old.case_number, old.court_id) then
    raise exception 'hearing_close_with_changes';
  end if;

  if new.status_id = 2 then
    if now() < old.scheduled_at + interval '1 hour' then
      raise exception 'hearing_too_early_to_close';
    end if;
    if new.recording_url is null then
      raise exception 'hearing_recording_required';
    end if;
  elsif new.status_id = 3 then
    if now() < old.scheduled_at then
      raise exception 'hearing_too_early_to_cancel';
    end if;
    if new.recording_url is not null then
      raise exception 'hearing_recording_only_realizada';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists hearings_rules on public.hearings;
create trigger hearings_rules
  before insert or update or delete on public.hearings
  for each row execute function public.hearings_rules();

revoke execute on function public.hearings_rules() from public, anon, authenticated;

