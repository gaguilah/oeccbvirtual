-- Audiencias, fase 1: tablas, reglas y permisos (docs/plan-audiencias.md).
--
-- Ciclo: Programada → Realizada (desde 1 hora después y con grabación) o Cancelada (desde la hora
-- programada). Una audiencia cerrada solo admite corregir la grabación de una Realizada. Las reglas
-- viven en el trigger hearings_rules y se aplican a toda escritura con usuario (dashboard o API);
-- el SQL Editor y la service role (sin usuario) no las aplican, como en Avisos de Remate.
--
-- Permisos por juzgado: audiencias.ver|crear|editar|eliminar (juzgado, oficina, director_oficina)
-- y audiencias.tipos (catálogo de tipos; solo superadmin).

