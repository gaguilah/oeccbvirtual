-- Días no hábiles de un rango para el calendario y el formulario. La tabla solo la lee quien tiene
-- calendario.ver; esto expone solo fecha y motivo a quien gestiona audiencias.
create or replace function public.hearing_non_business_days(p_from date, p_to date)
returns table (day date, reason text)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.has_permission('audiencias.ver') then
    raise exception 'forbidden' using errcode = '42501';
  end if;
  if p_to < p_from or p_to - p_from > 400 then
    raise exception 'invalid_period';
  end if;
  return query
    select n.day, n.reason from public.non_business_days n
    where n.day between p_from and p_to
    order by n.day;
end;
$$;

-- Quién creó y quién modificó por última vez (nombre o correo), para el detalle.
create or replace function public.hearing_audit(p_id uuid)
returns table (created_by_name text, updated_by_name text)
language sql
stable
security definer
set search_path = ''
as $$
  select
    coalesce(cp.full_name, cu.email::text),
    coalesce(up.full_name, uu.email::text)
  from public.hearings h
  left join public.profiles cp on cp.id = h.created_by
  left join auth.users cu on cu.id = h.created_by
  left join public.profiles up on up.id = h.updated_by
  left join auth.users uu on uu.id = h.updated_by
  where h.id = p_id
    and public.has_permission('audiencias.ver', h.court_id);
$$;

revoke execute on function public.hearing_schedule_error(timestamptz) from public, anon;
revoke execute on function public.hearing_non_business_days(date, date) from public, anon;
revoke execute on function public.hearing_audit(uuid) from public, anon;
grant execute on function public.hearing_schedule_error(timestamptz) to authenticated;
grant execute on function public.hearing_non_business_days(date, date) to authenticated;
grant execute on function public.hearing_audit(uuid) to authenticated;

